#include "fsl_common.h"
#include "ftm.h"


//==============================================================================
// DATA
//==============================================================================
volatile bool ftmIsrFlag           = false;
//==============================================================================
// CODE
//==============================================================================
void Init_FTM0(void)
{     
    ftm_config_t ftm_config;

//------------------------------------------------------------------------------ 
// Clock enabled
//------------------------------------------------------------------------------ 
    CLOCK_EnableClock(kCLOCK_Ftm0);     

//------------------------------------------------------------------------------ 
// FTM0 Init
//------------------------------------------------------------------------------ 
    FTM_GetDefaultConfig(&ftm_config);
    ftm_config.prescale = kFTM_Prescale_Divide_4;
    
    FTM_Init(FTM0, &ftm_config);
//------------------------------------------------------------------------------ 
// Configurate FTM0 period, FTM0 clock is 48MHz
//------------------------------------------------------------------------------ 
    FTM_SetTimerPeriod(FTM0,65536);
    FTM_EnableInterrupts(FTM0, kFTM_TimeOverflowInterruptEnable);
    NVIC_SetPriority(PIT0_IRQn, 3);
    EnableIRQ(FTM0_IRQn);
    
//------------------------------------------------------------------------------ 
// Start timer
//------------------------------------------------------------------------------ 
//    FTM_StartTimer(FTM0, kFTM_SystemClock);  
}


