void Init_PIT(void)
{     
    pit_config_t pit_config;

//------------------------------------------------------------------------------ 
// Clock enabled
//------------------------------------------------------------------------------ 
    CLOCK_EnableClock(kCLOCK_Pit0);     

//------------------------------------------------------------------------------ 
// PIT Init
//------------------------------------------------------------------------------ 
//    
    PIT_GetDefaultConfig(&pit_config);
    PIT_Init(PIT, &pit_config);
    
    PIT_EnableInterrupts(PIT, kPIT_Chnl_0, kPIT_TimerInterruptEnable);
    NVIC_SetPriority(PIT0_IRQn, 1);
    EnableIRQ(PIT0_IRQn);


    PIT_SetTimerPeriod(PIT, kPIT_Chnl_0, 24000);//1us=48,设置通讯周期为500us 2KHz Cycle*48
    //PIT_StartTimer(PIT, kPIT_Chnl_0);   
   
//------------------------------------------------------------------------------ 
// Configurate PIT period, PIT clock is 48MHz
//------------------------------------------------------------------------------ 
//    PIT_SetTimerPeriod(PIT, kPIT_Chnl_0, USEC_TO_COUNT(3000U, CLOCK_GetFreq(kCLOCK_BusClk)));//1000=2ms      
//------------------------------------------------------------------------------ 
// Start timer
//------------------------------------------------------------------------------  
//    PIT_StartTimer(PIT, kPIT_Chnl_0);
}


